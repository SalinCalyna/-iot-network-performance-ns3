#!/usr/bin/env python3
"""Build the dashboard data for the PSU Phuket smart-campus case study (read-only on analysis/).

    python3 -I -B experiments/wifi6-risk/build_site_campus.py <site dir>

Input: the frozen OpenStreetMap snapshot in analysis/campus-case-study/osm/ (ODbL, see its README).
Writes <site>/data/campus/campus.json:
  osm        campus boundary, buildings (with names where OSM has them), roads/paths and water inside the campus,
             as [lat, lon] rings/lines, plus attribution and snapshot sha256
  proposed   a CONCEPTUAL deployment generated by the fixed rule below (no surveyed or installed sensor exists)
  frame      the local metric frame used to place the 250 m x 250 m ns-3 field on the map
Proposed-deployment rule (deterministic; every point is derived from an OSM feature, nothing is hand-placed):
  environmental  centroid of every building whose centroid lies inside the campus boundary
  traffic        vertices shared by >= 2 vehicle roads (tertiary / residential / service / unclassified) inside the campus
  lighting       points every 70 m along every road and footway inside the campus
  flood          the northern, eastern, southern and western extreme vertices of each water polygon inside the campus
  gateway        default: centroid of the administration building (OSM way 627751851, about 25 m from the campus centre);
                 any named building may be chosen on the page instead
  A candidate closer than 30 m to an already accepted point is skipped (order: environmental, traffic, flood, lighting).
"""
import hashlib
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OSM = ROOT / "analysis/campus-case-study/osm"
SNAP = OSM / "overpass-campus-20261026.json"
CAMPUS_WAY, ADMIN_WAY = 316508940, 627751851
VEHICLE = {"tertiary", "residential", "service", "unclassified"}
LIGHT_STEP_M, MIN_SEP_M = 70.0, 30.0
K = 111320.0   # metres per degree of latitude (local equirectangular frame; error < 0.1 % over 1 km here)


def inside(pt, poly):   # ray casting, pt / poly in (x, y)
    x, y, c = pt[0], pt[1], False
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


def centroid(P):   # polygon area centroid
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(P, P[1:] + P[:1]):
        f = x1 * y2 - x2 * y1
        a += f
        cx += (x1 + x2) * f
        cy += (y1 + y2) * f
    if abs(a) < 1e-9:
        return (sum(p[0] for p in P) / len(P), sum(p[1] for p in P) / len(P))
    return (cx / (3 * a), cy / (3 * a))


def main():
    site = Path(sys.argv[1])
    raw = SNAP.read_bytes()
    d = json.loads(raw)
    E = d["elements"]
    camp = next(e for e in E if e["type"] == "way" and e["id"] == CAMPUS_WAY)
    lat0 = sum(p["lat"] for p in camp["geometry"]) / len(camp["geometry"])
    lon0 = sum(p["lon"] for p in camp["geometry"]) / len(camp["geometry"])
    cl = math.cos(math.radians(lat0))
    xy = lambda p: ((p["lon"] - lon0) * K * cl, (p["lat"] - lat0) * K)
    ll = lambda q: [round(lat0 + q[1] / K, 7), round(lon0 + q[0] / (K * cl), 7)]
    B = [xy(p) for p in camp["geometry"]]
    if B[0] == B[-1]:
        B = B[:-1]
    ways = [e for e in E if e["type"] == "way" and e["id"] != CAMPUS_WAY and "geometry" in e]
    buildings, roads, water = [], [], []
    for e in ways:
        t, P = e.get("tags", {}), [xy(p) for p in e["geometry"]]
        if "building" in t:
            c = centroid(P[:-1] if P[0] == P[-1] else P)
            if inside(c, B):
                buildings.append(dict(id=e["id"], name=t.get("name:en") or t.get("name"), name_th=t.get("name"), kind=t.get("building"), c=c, P=P))
        elif "highway" in t:
            seg = [p for p in P if inside(p, B)]   # keep the vertices inside the campus
            if len(seg) >= 2:
                roads.append(dict(id=e["id"], kind=t["highway"], name=t.get("name:en") or t.get("name"), P=seg,
                                  geo=[(g["lat"], g["lon"]) for g, p in zip(e["geometry"], P) if inside(p, B)]))
        elif t.get("natural") == "water" and inside(centroid(P), B):
            water.append(dict(id=e["id"], name=t.get("name"), P=P))
    admin = next(b for b in buildings if b["id"] == ADMIN_WAY)

    pts = []
    def add(p, app, src):
        if all(math.dist(p, q["xy"]) >= MIN_SEP_M for q in pts):
            pts.append(dict(xy=p, app=app, src=src))
    for b in buildings:
        add(b["c"], "environmental", f"building centroid, OSM way {b['id']}" + (f" ({b['name']})" if b["name"] else ""))
    # junctions: a vertex (identical lat/lon, i.e. the same OSM node) shared by >= 2 vehicle roads
    ways_at, where = {}, {}
    for r in roads:
        if r["kind"] in VEHICLE:
            for g, p in zip(r["geo"], r["P"]):
                ways_at.setdefault(g, set()).add(r["id"])
                where[g] = p
    for g in sorted(ways_at):
        if len(ways_at[g]) >= 2:
            add(where[g], "traffic", f"road junction at {g[0]:.7f}, {g[1]:.7f} ({len(ways_at[g])} roads)")
    for w in water:
        P = w["P"]
        for name, f in (("north", lambda p: p[1]), ("east", lambda p: p[0]), ("south", lambda p: -p[1]), ("west", lambda p: -p[0])):
            add(max(P, key=f), "flood", f"{name} edge of water body OSM way {w['id']}" + (f" ({w['name']})" if w["name"] else ""))
    for r in sorted(roads, key=lambda r: r["id"]):
        P, acc = r["P"], 0.0
        add(P[0], "lighting", f"along {r['kind']} OSM way {r['id']}")
        for a, b in zip(P, P[1:]):
            L = math.dist(a, b)
            while acc + L >= LIGHT_STEP_M:
                t = (LIGHT_STEP_M - acc) / L
                a = (a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1]))
                L = math.dist(a, b)
                acc = 0.0
                add(a, "lighting", f"along {r['kind']} OSM way {r['id']}")
            acc += L
    # gateway candidates: named buildings (default: administration building); sensors keep their position
    gws = [dict(id=b["id"], name=b["name"] or b["name_th"], xy=[round(b["c"][0], 2), round(b["c"][1], 2)], ll=ll(b["c"]))
           for b in buildings if b["name"] or b["name_th"]]
    gws.sort(key=lambda g: (g["id"] != ADMIN_WAY, g["name"]))
    out = dict(
        generated_by="experiments/wifi6-risk/build_site_campus.py",
        attribution="© OpenStreetMap contributors (ODbL 1.0)",
        osm_snapshot=dict(file=str(SNAP.relative_to(ROOT)), sha256=hashlib.sha256(raw).hexdigest(),
                          osm_timestamp=d.get("osm3s", {}).get("timestamp_osm_base"), campus_way=CAMPUS_WAY),
        frame=dict(lat0=lat0, lon0=lon0, m_per_deg_lat=K, m_per_deg_lon=K * cl,
                   note="local equirectangular frame centred on the campus polygon's vertex mean; x east, y north, metres"),
        campus=dict(name=camp["tags"].get("name:en"), name_th=camp["tags"].get("name"), ring=[ll(p) for p in B],
                    area_m2=round(abs(sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(B, B[1:] + B[:1]))) / 2)),
        buildings=[dict(id=b["id"], name=b["name"], name_th=b["name_th"], kind=b["kind"], ring=[ll(p) for p in b["P"]]) for b in buildings],
        roads=[dict(id=r["id"], kind=r["kind"], name=r["name"], line=[ll(p) for p in r["P"]]) for r in roads],
        water=[dict(id=w["id"], name=w["name"], ring=[ll(p) for p in w["P"]]) for w in water],
        proposed=dict(rule=dict(lighting_step_m=LIGHT_STEP_M, min_separation_m=MIN_SEP_M, vehicle_roads=sorted(VEHICLE)),
                      sensors=[dict(id=i, app=p["app"], xy=[round(p["xy"][0], 2), round(p["xy"][1], 2)], ll=ll(p["xy"]), src=p["src"])
                               for i, p in enumerate(pts)],
                      gateways=gws, default_gateway=ADMIN_WAY))
    (site / "data/campus").mkdir(parents=True, exist_ok=True)
    (site / "data/campus/campus.json").write_text(json.dumps(out, separators=(",", ":"), ensure_ascii=False) + "\n")
    apps = {}
    for p in pts:
        apps[p["app"]] = apps.get(p["app"], 0) + 1
    print(f"wrote campus.json: {len(buildings)} buildings, {len(roads)} road segments, {len(water)} water, "
          f"{len(pts)} proposed sensors {apps}, {len(gws)} gateway candidates; admin building {admin['name']} "
          f"at {math.dist(admin['c'], (0, 0)):.0f} m from the campus centre")


if __name__ == "__main__":
    main()
