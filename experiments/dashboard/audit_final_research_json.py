#!/usr/bin/env python3
"""Audit site/data/final_research.json against the frozen Final Report Data Package (read-only).

    python3 -I -B experiments/dashboard/audit_final_research_json.py

final_research.json is a hand-curated extract (analysis/final-github-release/FINAL_GITHUB_RELEASE_REPORT.md),
not generated by a script. This compares every numeric field that has a counterpart in
analysis/final-report-data/*.csv or analysis/bottleneck-characterisation/T_probe_hopbin_by_cell.csv. A value passes
when it equals the CSV value at the CSV's own printed precision (half a unit in the last printed digit, plus a
1e-9 floor). Prints one line per block and every mismatch; exit code 1 on any mismatch.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / "analysis/final-report-data"
J = json.loads((ROOT / "site/data/final_research.json").read_text())
bad, n_ok = [], 0


def rows(p):
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def tol(s):
    s = s.strip().lstrip("+").rstrip("%")
    return 0.5 * 10 ** -(len(s.split(".")[1])) if "." in s else 0.5


def num(s):
    return float(s.strip().lstrip("+").rstrip("%").replace(",", ""))


def cmp(block, key, jv, cs, scale=1.0):
    """scale: JSON unit / CSV unit (e.g. 1000 when the JSON stores ms and the CSV stores s)."""
    global n_ok
    if cs is None or cs.strip() in ("", "n/a", "NA", "nan"):
        if jv is None:
            n_ok += 1
            return
        bad.append((block, key, jv, cs))
        return
    if jv is None or abs(float(jv) - scale * num(cs)) > scale * tol(cs) + 1e-9:
        bad.append((block, key, jv, cs))
    else:
        n_ok += 1


def main():
    global n_ok
    # V3 baseline
    v3 = {(r["protocol"], int(r["node_count"])): r for r in rows(PKG / "v3_core_results.csv")}
    for p, lst in J["baseline"].items():
        for d in lst:
            r = v3[(p, d["n"])]
            for jk, ck, sc in (("pdr", "pdr_mean", 1), ("pdr_sd", "pdr_sd", 1), ("throughput", "throughput_mean_kbps", 1),
                               ("delay", "delay_mean_s", 1000), ("jitter", "jitter_mean_s", 1000),   # JSON ms, CSV s
                               ("loss", "packet_loss_mean", 1), ("hop", "mean_hop_count", 1)):
                cmp("baseline", f"{p} N={d['n']} {jk}", d.get(jk), r[ck], sc)
    # bottleneck
    bn = {(r["protocol"], int(r["N"]), r["traffic"]): r for r in rows(PKG / "bottleneck_results.csv")}
    for key, lst in J["bottleneck"].items():
        p, t = key.split("-")
        for d in lst:
            r = bn[(p, d["n"], t)]
            for jk, ck in (("gw_airtime", "gw_airtime"), ("ring1_airtime", "ring1_airtime"), ("macq", "mac_queue_drops_mean"),
                           ("phyrx", "phy_rx_drops_mean"), ("pdr", "PDR_mean"), ("throughput", "throughput_kbps"),
                           ("no_route", "NO_ROUTE_mean"), ("route_error", "ROUTE_ERROR_mean"), ("frac_nodes_le1", "frac_nodes_hop_le1"),
                           ("frac_macq_le1", "frac_macq_hop_le1"), ("macq_conc", "macq_concentration_ratio")):
                cmp("bottleneck", f"{key} N={d['n']} {jk}", d.get(jk), r[ck])
    # hop bins
    hb = {(r["protocol"], int(r["nodes"]), r["trafficLevel"], r["hop_bin"]): r
          for r in rows(ROOT / "analysis/bottleneck-characterisation/T_probe_hopbin_by_cell.csv")}
    for key, lst in J["hopbin"].items():
        p, n, t = key.split("-")
        for d in lst:
            r = hb.get((p, int(n), t, d["bin"]))
            if r is None:
                bad.append(("hopbin", f"{key} {d['bin']}", "no CSV row", None))
                continue
            for jk, ck in (("n_nodes", "n_nodes_per_seed_mean"), ("airtime", "airtime_busy_frac_node_mean"),
                           ("macq", "mac_queue_drops_node_mean"), ("phyrx", "phy_rx_drops_node_mean")):
                cmp("hopbin", f"{key} {d['bin']} {jk}", d.get(jk), r[ck])
    # retry
    rt = {(r["protocol"], int(r["N"]), r["traffic"]): r for r in rows(PKG / "retry_results.csv")}
    for d in J["retry"]:
        r = rt[(d["protocol"], d["n"], d["traffic"])]
        for jk, ck in (("retry_pct", "retry_pct_of_loss"), ("macq_pct", "macq_pct_of_loss"), ("accounted_pct", "accounted_pct_of_loss")):
            cmp("retry", f"{d['protocol']} N={d['n']} {d['traffic']} {jk}", d.get(jk), r[ck])
    # rate sweep
    rs = {(r["protocol"], int(r["N"]), int(r["rate_kbps"])): r for r in rows(PKG / "rate_sweep_results.csv")}
    for key, lst in J["ratesweep"].items():
        p, n = key.split("-")
        for d in lst:
            r = rs[(p, int(n), int(d["rate"]))]
            for jk, ck in (("pdr", "pdr_mean"), ("throughput", "throughput_mean"), ("gw_airtime", "gw_airtime_mean"),
                           ("macq", "mac_queue_drops_mean"), ("retry", "max_retry_drops_mean"), ("delta_pdr_pp", "delta_pdr_pp_vs_16kbps")):
                cmp("ratesweep", f"{key} {d['rate']}kbps {jk}", d.get(jk), r[ck])
    # Static N=50 diagnostic
    dg = {(int(r["rate_kbps"]), int(r["seed"])): r for r in rows(PKG / "static_n50_diagnostic.csv")}
    for d in J["diagnostic"]:
        r = dg[(d["rate"], d["seed"])]
        for jk, ck in (("pdr", "PDR"), ("loss", "total_packet_loss"), ("attributable_pct", "attributable_pct"), ("residual_pct", "residual_pct")):
            cmp("diagnostic", f"{d['rate']}kbps seed {d['seed']} {jk}", d.get(jk), r[ck])
    # V4
    v4 = rows(PKG / "v4_results.csv")
    vm = {int(r["N"]): r for r in v4 if r["section"] == "V4-matched"}
    for d in J["v4_matched"]:
        r = vm[d["n"]]
        cmp("v4_matched", f"N={d['n']} pdr_v4", d["pdr_v4"], r["PDR_v4"])
        cmp("v4_matched", f"N={d['n']} pdr_static", d["pdr_static"], r["PDR_static"])
    t1 = [r for r in v4 if r["section"].startswith("V4-Tier1")]
    for d, r in zip(J["v4_tier1"], t1):
        if d["condition"] != r["condition"]:
            bad.append(("v4_tier1", "condition", d["condition"], r["condition"]))
        for jk, ck in (("pdr_v4", "PDR_v4"), ("pdr_static", "PDR_static")):
            cmp("v4_tier1", f"{d['condition']} {jk}", d.get(jk), r[ck])
        for jk, ck in (("route_change_pct", "route_tree_differs_from_static_pct"), ("hop_diff_pct", "hop_diff_pct"),
                       ("delay_diff_pct", "delay_diff_pct")):   # stored verbatim as text in both files
            if str(d.get(jk)) != r[ck]:
                bad.append(("v4_tier1", f"{d['condition']} {jk}", d.get(jk), r[ck]))
            else:
                n_ok += 1
        act = r["ACTIVATED"].strip().lower().startswith("true")
        if str(d["activated"]).lower().startswith("true") != act:
            bad.append(("v4_tier1", f"{d['condition']} activated", d["activated"], r["ACTIVATED"]))
        else:
            n_ok += 1
    print(f"checked {n_ok + len(bad)} values: {n_ok} match, {len(bad)} mismatch")
    for b in bad:
        print("  MISMATCH", b)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
